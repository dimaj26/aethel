import argparse
import os
import shutil
import sys

from aethel.linter import run_linter

TEMPLATES_DIR = os.path.join(os.path.dirname(__file__), "templates")


# Helper to copy template files
def copy_template(src_name: str, dest_name: str, dest_dir: str, overwrite: bool = False) -> bool:
    src_path = os.path.join(TEMPLATES_DIR, src_name)
    dest_path = os.path.join(dest_dir, dest_name)

    if not os.path.exists(src_path):
        print(f"Error: Template source '{src_path}' not found.")
        return False

    if os.path.exists(dest_path) and not overwrite:
        print(f"Skipping existing file: {dest_name}")
        return False

    shutil.copy2(src_path, dest_path)
    print(f"Created/Updated: {dest_name}")
    return True


# Helper to recursively copy directories
def copy_template_dir(src_name: str, dest_name: str, dest_dir: str, overwrite: bool = False) -> bool:
    src_path = os.path.join(TEMPLATES_DIR, src_name)
    dest_path = os.path.join(dest_dir, dest_name)

    if not os.path.exists(src_path):
        print(f"Error: Template folder source '{src_path}' not found.")
        return False

    if os.path.exists(dest_path):
        if overwrite:
            shutil.rmtree(dest_path)
        else:
            print(f"Skipping existing folder: {dest_name}")
            return False

    shutil.copytree(src_path, dest_path)
    print(f"Created/Updated folder: {dest_name}")
    return True


def cmd_init(args: argparse.Namespace) -> None:
    dest_dir = os.path.abspath(args.path)
    print(f"Initializing Aethel in: {dest_dir}")
    os.makedirs(dest_dir, exist_ok=True)

    # 1. Copy templates
    copy_template("gitattributes.template", ".gitattributes", dest_dir, overwrite=args.force)
    copy_template("GEMINI.md.template", "GEMINI.md", dest_dir, overwrite=args.force)
    copy_template("CONTEXT.md.template", "CONTEXT.md", dest_dir, overwrite=args.force)
    copy_template("memory.json.template", "memory.json", dest_dir, overwrite=args.force)
    copy_template("README.md.template", "README.md", dest_dir, overwrite=args.force)

    # 2. Copy .agents plugin
    copy_template_dir(".agents", ".agents", dest_dir, overwrite=args.force)

    # 3. Create wrapper prompt_linter.py
    linter_wrapper_path = os.path.join(dest_dir, "prompt_linter.py")
    if os.path.exists(linter_wrapper_path) and not args.force:
        print("Skipping existing prompt_linter.py wrapper.")
    else:
        with open(linter_wrapper_path, "w", encoding="utf-8") as f:
            f.write("""#!/usr/bin/env python3
# Autogenerated Aethel wrapper script
import sys
try:
    from aethel.linter import run_linter
except ImportError:
    print("Error: 'aethel' package not found in Python path. Please run 'pip install aethel' or install it globally.")
    sys.exit(1)

if __name__ == "__main__":
    success = run_linter()
    sys.exit(0 if success else 1)
""")
        print("Created prompt_linter.py wrapper script.")

    print("Aethel initialization complete. Please configure your Memory MCP server path in README.md.")


def cmd_lint(args: argparse.Namespace) -> None:
    dest_dir = os.path.abspath(args.path)
    print(f"Linting Aethel workspace: {dest_dir}")
    success = run_linter(dest_dir)
    sys.exit(0 if success else 1)


def cmd_update(args: argparse.Namespace) -> None:
    dest_dir = os.path.abspath(args.path)
    print(f"Updating central Aethel structures in: {dest_dir}")

    # 1. Overwrite system files
    copy_template("gitattributes.template", ".gitattributes", dest_dir, overwrite=True)
    copy_template_dir(".agents", ".agents", dest_dir, overwrite=True)

    # 2. Backup and update rule files
    gemini_path = os.path.join(dest_dir, "GEMINI.md")
    if os.path.exists(gemini_path):
        backup_path = gemini_path + ".bak"
        shutil.copy2(gemini_path, backup_path)
        print(f"Created backup of GEMINI.md at {backup_path}")

    copy_template("GEMINI.md.template", "GEMINI.md", dest_dir, overwrite=True)

    # 3. Re-create linter wrapper
    linter_wrapper_path = os.path.join(dest_dir, "prompt_linter.py")
    with open(linter_wrapper_path, "w", encoding="utf-8") as f:
        f.write("""#!/usr/bin/env python3
# Autogenerated Aethel wrapper script
import sys
try:
    from aethel.linter import run_linter
except ImportError:
    print("Error: 'aethel' package not found in Python path. Please run 'pip install aethel' or install it globally.")
    sys.exit(1)

if __name__ == "__main__":
    success = run_linter()
    sys.exit(0 if success else 1)
""")
    print("Updated prompt_linter.py wrapper script.")
    print("Central structures successfully updated.")


def main() -> None:
    parser = argparse.ArgumentParser(description="Aethel: AI Context & Memory CLI Management Utility")
    subparsers = parser.add_subparsers(dest="command", help="Commands to run")

    # init subcommand
    p_init = subparsers.add_parser("init", help="Initialize Aethel in a workspace")
    p_init.add_argument("path", nargs="?", default=".", help="Directory to initialize (default: current)")
    p_init.add_argument("-f", "--force", action="store_true", help="Force overwrite of existing files")
    p_init.set_defaults(func=cmd_init)

    # lint subcommand
    p_lint = subparsers.add_parser("lint", help="Validate workspace plan files and memory.json integrity")
    p_lint.add_argument("path", nargs="?", default=".", help="Workspace path to lint (default: current)")
    p_lint.set_defaults(func=cmd_lint)

    # update subcommand
    p_update = subparsers.add_parser("update", help="Update Aethel core files & plugins to latest version")
    p_update.add_argument("path", nargs="?", default=".", help="Workspace path to update (default: current)")
    p_update.set_defaults(func=cmd_update)

    args = parser.parse_args()
    if not args.command:
        parser.print_help()
        sys.exit(1)

    # Fetch and call the registered subcommand function
    func = getattr(args, "func", None)
    if func:
        func(args)
    else:
        parser.print_help()
        sys.exit(1)


if __name__ == "__main__":
    main()
